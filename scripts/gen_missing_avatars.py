# 年龄粗判:由生卒年推,无法判断时按身份 defaults
def age_desc(birth, death, identity, is_female=False):
    """is_female=True 时返回女性专用年龄描述,不出现"须髯"等男性特征词"""
    if birth is None or death is None:
        if any(k in identity for k in ["老将", "老臣", "太后", "老儒", "高僧", "药王", "隐士"]):
            return "老年,白发长眉,面容沧桑" if is_female else "老年,白发长须,面容沧桑"
        if any(k in identity for k in ["少年", "童子", "少年天子", "少女"]):
            return "少年,面容青涩"
        if any(k in identity for k in ["青年", "帅哥", "美男子", "美女", "佳人", "少女"]):
            return "青年,面容俊朗" if not is_female else "青年,清丽动人"
        return "中年"
    age_at_death = abs(death - birth)
    if age_at_death >= 70:
        return "老年,白发,面容慈祥沧桑" if is_female else "老年,须发花白,面容沧桑"
    if age_at_death >= 50:
        return "中年,面容沉稳端庄" if is_female else "中年,面容沉稳,略有须髯"
    if age_at_death >= 30:
        return "壮年,面容英挺" if not is_female else "壮年,风韵成熟"
    return "青年,面容清俊" if not is_female else "青年,清丽秀美"


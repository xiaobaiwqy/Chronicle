def feature_cn(name, identity, summary):
    # 优先用手写的专属形象关键词
    if name in FEATURE_HINTS:
        return FEATURE_HINTS[name]
    # 没有就用"身份+小传第一句"拼,且尽量取关键词
    base = (identity or "").replace("、", ",")
    if summary:
        base += "," + summary.split(",")[0].split("。")[0]
    return (base or "面容端肃,气质沉稳").strip(",")

def feature_en(feat_cn, name, dynasty, identity):
    # 英译要点辅助(简单关键词,不追求完美)
    kw = [k.strip() for k in feat_cn.split(",") if k.strip()]
    return f"A portrait of {name} ({dynasty} dynasty), {identity}. Key features: " + "; ".join(kw[:4])

def style_for(name: str) -> dict:
    """按人物名哈希选一个画风变体,保证同一批图风格不雷同。"""
    import zlib
    idx = zlib.crc32(name.encode("utf-8")) % len(STYLE_VARIANTS)
    return STYLE_VARIANTS[idx]

def build_prompt(name, dynasty, identity, birth, death, summary, style_tmpl):
    gender = gender_desc(name, identity)
    is_female = gender.startswith("女性")
    age = age_desc(birth, death, identity, is_female=is_female)
    feat = feature_cn(name, identity, summary)
    feat_en = feature_en(feat, name, dynasty, identity)
    style = style_for(name)
    return style_tmpl.format(
        name=name, dynasty=dynasty, gender=gender, age=age,
        identity=identity, feat=feat, feat_cn=feat, feat_en=feat_en,
        dyn_kw=DYNASTY_STYLE.get(dynasty, "古代人物"),
        style_variant=style["prompt"], style_name=style["name"],
    )

def db_has_persons(db_path: Path) -> bool:
    """检查数据库是否含 persons 表(用于 find_db 过滤无效库)"""
    try:
        import sqlite3
        con = sqlite3.connect(str(db_path))
        cur = con.cursor()
        cur.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='persons'")
        ok = cur.fetchone() is not None
        con.close()
        return ok
    except Exception:
        return False

def find_db() -> Path:
    # 优先找:用户正在使用的 app 数据库(有 persons 表的 chronicle*.db)
    candidates = sorted(
        glob.glob(str(DEFAULT_DB_DIR.parent.parent / "**/chronicle*.db"), recursive=True) +
        glob.glob(str(Path.home() / "Library/Application Support/chronicle-desktop/sqlite/chronicle*.db")),
        key=os.path.getmtime, reverse=True
    )
    good = [Path(p) for p in candidates if db_has_persons(Path(p))]
    if good:
        return good[0]
    if candidates:
        print("警告:找到数据库但均无 persons 表,取最新者", file=sys.stderr)
        return Path(candidates[0])
    sys.exit(f"找不到数据库文件,请用 --db 指定")
    return Path(candidates[0])

def load_persons(db_path: Path):
    import sqlite3
    con = sqlite3.connect(str(db_path))
    cur = con.cursor()
    cur.execute("SELECT id, name, dynasty, identity, birth_year, death_year, summary FROM persons ORDER BY id")
    rows = cur.fetchall()
    con.close()
    return [
        {"id": r[0], "name": r[1].strip(), "dynasty": r[2] or "", "identity": r[3] or "",
         "birth": r[4], "death": r[5], "summary": r[6] or ""}
        for r in rows if r[1]
    ]

def out_path(out_dir: Path, name: str) -> Path:
    return out_dir / f"{name}.jpg"

def existing_ok(p: Path) -> bool:
    return p.exists() and p.stat().st_size > 20_000

# 头像已存在判定:avatars/ 根目录(用户已有 486 个) 或 supply/ 输出目录下任一有同名文件即视为已有,不生成
def person_has_avatar(name: str, out_dir: Path) -> bool:
    main_dir = DEFAULT_DB_DIR / "avatars"
    return existing_ok(main_dir / f"{name}.jpg") or existing_ok(main_dir / f"{name}.png") or existing_ok(out_path(out_dir, name))

def gen_one(person, out_dir: Path, style_tmpl: str):
    dest = out_path(out_dir, person["name"])
    if person_has_avatar(person["name"], out_dir):
        return (person["name"], "skip", 0)
    prompt = build_prompt(person["name"], person["dynasty"], person["identity"], person["birth"], person["death"], person["summary"], style_tmpl)
    payload = {"model": args.model, "prompt": prompt, "size": args.size}  # seedream 端点仅需 model+prompt,size 可选(锁定 1024x1024 与现有头像一致)
    headers = {"Content-Type": "application/json", "Authorization": f"Bearer {API_KEY}"}
    last_err = ""
    for attempt in range(1, MAX_RETRY + 1):
        try:
            r = requests.post(URL, json=payload, headers=headers, timeout=180)
            if r.status_code != 200:
                last_err = f"HTTP {r.status_code}: {r.text[:200]}"
                time.sleep(2 * attempt); continue
            d = r.json()
            item = d.get("data", [{}])[0]
            img = None
            if item.get("b64_json"):
                img = base64.b64decode(item["b64_json"])
            elif item.get("url"):
                ir = requests.get(item["url"], timeout=60)
                if ir.status_code == 200:
                    img = ir.content
            if not img or len(img) < 20_000:
                last_err = f"response 无有效图像 data keys={list(d.keys())} item keys={list(item.keys())} summary={str(d)[:200]}"
                time.sleep(2 * attempt); continue
            dest.write_bytes(img)
            return (person["name"], "OK", len(img) // 1024)
        except Exception as e:
            last_err = f"exception: {e!r}"
            time.sleep(2 * attempt)
    return (person["name"], "FAIL", 0, last_err)

def main():
    global args
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", type=str, default="", help="数据库文件路径")
    ap.add_argument("--workers", type=int, default=6)
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--out", type=str, default=str(DEFAULT_OUT_DIR))
    ap.add_argument("--size", type=str, default="1024x1024")
    ap.add_argument("--style", type=str, default=str(STYLE_PATH))
    ap.add_argument("--model", type=str, default="seedream-image-v5.0-pro", help="生图模型名")
    ap.add_argument("--quality", type=str, default="high", help="画质 high/low")
    ap.add_argument("--yes", action="store_true", help="跳过重名确认(脚本默认可直接跑)")
    args = ap.parse_args()

    db_path = Path(args.db) if args.db else find_db()
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    style_tmpl = load_style()

    persons = load_persons(db_path)
    todo = [p for p in persons if not person_has_avatar(p["name"], out_dir)]
    if args.limit:
        todo = todo[:args.limit]

    print(f"数据库人物 {len(persons)} 位,待生成 {len(todo)} 位(仅在 avatars 与 supply 下均不存在的才生成),输出目录 {out_dir},并行 {args.workers}")
    if not todo:
        print("全部已生成完毕 ✔"); return

    lock = threading.Lock()
    done = fail = 0
    t0 = time.time()
    with ThreadPoolExecutor(max_workers=args.workers) as ex:
        futs = {ex.submit(gen_one, p, out_dir, style_tmpl): p for p in todo}
        for fut in as_completed(futs):
            name, st, kb, *rest = fut.result()
            err = rest[0] if rest else ""
            with lock:
                if st in ("OK", "skip"): done += 1
                else: fail += 1
                n = done + fail
                el = time.time() - t0
                eta = el / n * (len(todo) - n) if n else 0
                suffix = f"  {err}" if err else ""
                print(f"[{n}/{len(todo)}] {name:8} {st:4} {kb:4}KB  已用 {el/60:.1f} 分  剩 {eta/60:.1f} 分{suffix}", flush=True)
    print(f"\n=== 完成 {done} 张,失败 {fail} 张 ===")

if __name__ == "__main__":
    main()
